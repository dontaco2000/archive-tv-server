#!/bin/sh
# Regenerates lib/src/header_logo.dart (embedded so an AOT server needs no asset files) from the approved
# Archive TV branding wordmark (icon + ARCHIVE TV). Run from the package root; ffmpeg + python on PATH.
SRC="${1:?usage: tool/make_logo.sh <path to logo-wordmark.png>}"
ffmpeg -hide_banner -loglevel error -y -i "$SRC" -vf "scale=208:78:flags=lanczos,format=rgba" assets/header_logo.png
python - <<'PY'
import base64
b=base64.b64encode(open('assets/header_logo.png','rb').read()).decode()
lines=[b[i:i+100] for i in range(0,len(b),100)]
open('lib/src/header_logo.dart','w').write("// GENERATED by tool/make_logo.sh from Archive TV _build/branding/final/logo-wordmark.png (1600x600)\n// scaled to 208x78 (lanczos) = assets/header_logo.png.\nconst headerLogoPngBase64 =\n"+"\n".join("    '%s'"%l for l in lines)+";\n")
PY
